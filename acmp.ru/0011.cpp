// В нашем зоопарке появился заяц. Его поместили в клетку, и чтобы ему не было скучно,
// директор зоопарка распорядился поставить в его клетке лесенку. Теперь наш зайчик может
// прыгать по лесенке вверх, перепрыгивая через ступеньки. Лестница имеет определенное
// количество ступенек N. Заяц может одним прыжком преодолеть не более К ступенек. Для
// разнообразия зайчик пытается каждый раз найти новый путь к вершине лестницы. Директору
// любопытно, сколько различных способов есть у зайца добраться до вершины лестницы при
// заданных значениях K и N. Помогите директору написать программу, которая поможет вычислить
// это количество. Например, если K=3 и N=4, то существуют следующие маршруты: 1+1+1+1,
// 1+1+2, 1+2+1, 2+1+1, 2+2, 1+3, 3+1. Т.е. при данных значениях у зайца всего 7 различных
// маршрутов добраться до вершины лестницы.
//
// Входные данные: в единственной строке входного файла INPUT.TXT записаны два натуральных
// числа K и N (1 ≤ K ≤ N ≤ 300). К - максимальное количество ступенек, которое может
// преодолеть заяц одним прыжком, N – общее число ступенек лестницы.
//
// Выходные данные: в единственную строку выходного файла OUTPUT.TXT нужно вывести количество
// возможных вариантов различных маршрутов зайца на верхнюю ступеньку лестницы без ведущих
// нулей.
//
// Примеры:
//   1 3 → 1
//   2 7 → 21
//   3 10 → 274
//
// Свой тест на максимум (ответ из 91 цифры — в long long не влезает):
//   300 300 → 1018517988167243043134222844204689080525734196832968125318070224677190649881668353091698688

#include <iostream>
#include <string>
#include <vector>
#include <algorithm>

using namespace std;

string add(string a, string b) {
    string result = "";

    int i = a.length() -1;
    int j = b.length() -1;

    int carry = 0;

    while (i>=0 or j>=0 or carry > 0) {
        int sum = carry;

        if (i >=0) {
            sum += a[i] - '0';
            i--;
        }

        if (j >=0) {
            sum += b[j] - '0';
            j--;
        }

        carry = sum/10;
        result.push_back((sum%10) + '0');
    }
    reverse(result.begin(), result.end());
    return result;
}


int main() {
    int n;
    int k;
    cin >> k;
    cin >> n;

    vector<string> ways(n+1, "0");
    ways[0] = "1";

    for (int i=1; i<=n; i++) {
        for (int j=1; j<=k; j++) {
            if(i-j >=0) {
                ways[i] = add(ways[i], ways[i - j]);
            }
        }
    }
    cout << ways[n];

}
