//
// В каждом запросе вы выбираете вершину x и перестановку p_1, p_2, …, p_n целых чисел
// от 1 до n, а интерактор возвращает
//     сумму по i от 1 до n значений  max { p_j : j ∈ path(i, x) },
// где path(i, x) — множество вершин на простом пути между i и x, включая обе вершины i и x
// (в частности, path(x, x) = {x}).
//
// Иными словами, для каждой вершины i рассмотрите все вершины j на единственном пути от i
// до x, включая оба конца пути, и возьмите наибольшее значение p_j среди них. Интерактор
// возвращает сумму этих максимальных значений по всем n вершинам i.
//
