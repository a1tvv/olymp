// количество вершин в дереве. Гарантируется, что сумма n по всем наборам не превосходит 500.
//
// Протокол взаимодействия: чтобы сделать запрос, выведите строку в формате
// «? x p_1 p_2 … p_n» (1 ≤ x ≤ n, а p_1, …, p_n — перестановка целых чисел от 1 до n).
// После каждого запроса считайте одно целое число — ответ на запрос. В каждом наборе можно
// сделать не более 2n−2 запросов.
//
// Когда вы найдёте дерево, выведите строку, содержащую «!», а затем n−1 строк, каждая из
// которых содержит два целых числа u и v, означающих, что между вершинами u и v есть ребро.
// Рёбра можно выводить в любом порядке. Вывод ответа не считается запросом. После вывода
